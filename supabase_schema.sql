-- Este script es aditivo e idempotente: nunca elimina tablas ni registros
-- ACTIVOS. Una instalación que aún tenga users.id debe migrarse con una
-- migración versionada y respaldada; convertir su PK y sus FK automáticamente
-- requiere reconstruir tablas y no es seguro hacerlo al ejecutar el esquema base.

-- Única excepción a la regla aditiva: las tablas legacy que la app dejó de
-- usar (exercises, workouts, workout_exercises, meals, meals_v2 y progress)
-- se eliminan si aún existen en una instalación anterior. Están vacías tras la
-- limpieza de la app y no forman parte del esquema actual; el modelo activo usa
-- exercises_v2, meal_logs, weekly_meal_plan y el resto de tablas definidas aquí.
-- Idempotente: DROP TABLE IF EXISTS no estorba en instalaciones nuevas.
drop table if exists public.workout_exercises cascade;
drop table if exists public.workouts cascade;
drop table if exists public.exercises cascade;
drop table if exists public.meals cascade;
drop table if exists public.meals_v2 cascade;
drop table if exists public.progress cascade;

-- ---------------- usuarios ----------------
-- El EMAIL es la clave primaria (identidad unica de la cuenta, igual que en
-- SQLite local); el antiguo id identity queda fuera del modelo.
create table if not exists public.users (
  email text primary key,
  name text not null,
  password_hash text,
  auth_provider text default 'local',
  created_at text default (now()::text)
);

-- UNIQUE(email) (redundante con la PK) para compatibilidad con el upsert por
-- correo idempotente. Idempotente.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.users'::regclass
      and contype = 'u'
      and conname = 'users_email_key'
  ) then
    alter table public.users
      add constraint users_email_key unique (email);
  end if;
end $$;

create table if not exists public.user_profiles (
  user_id text primary key,
  age integer,
  height double precision,
  current_weight double precision,
