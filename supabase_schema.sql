-- Asegura que 'user_profiles' tenga TODAS las columnas del modelo actual en
-- instalaciones donde la tabla se creó con una versión anterior del script
-- (p. ej. sin 'age'): CREATE TABLE IF NOT EXISTS no añade columnas a una tabla
-- ya existente. Cada ADD COLUMN IF NOT EXISTS es idempotente y no borra datos.
