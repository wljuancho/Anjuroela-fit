-- ============================================================
--  Borrado en cascada de la cuenta (datos del usuario)
--  Al eliminar una fila de `users` (desde el panel de Supabase o desde la
--  app), se borran también todas sus filas en las tablas de usuario que NO
--  tienen columna user_id y cuyo dueño se conoce solo por user_row_owners:
--  rutinas, sesiones, series, peso, comidas y plan semanal. Las tablas que ya
--  tienen FK a users (user_profiles, nutrition_profile, user_row_owners) se
--  limpian solas con ON DELETE CASCADE.
--  SECURITY DEFINER: el borrado se ejecuta como dueño de la función y no
--  depende de la cabecera x-app-user ni de RLS (funciona desde el panel).
--  Whitelist FIJA de tablas: nunca se usan table_name dinámicos de origen
--  externo, por lo que no hay riesgo de inyección/escalada pese al rol.
--  Idempotente: create or replace + drop trigger + create trigger permiten
--  re-ejecutar el script completo sin errores ni pérdida de datos.
-- ============================================================
create or replace function public.cascade_delete_user_data()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  t text;
begin
  foreach t in array array[
    'weekly_schedule','day_muscles','day_exercises','workout_sessions',
    'workout_sets','workout_circuits','weight_logs','meal_logs',
    'daily_calories','weekly_meal_plan'
  ]
  loop
    execute format(
      'delete from public.%I where id in
         (select row_id from public.user_row_owners
          where table_name = %L and user_id = %L)',
      t, t, old.email
    );
  end loop;
  return old;
end;
$$;

drop trigger if exists trg_users_cascade_delete on public.users;
create trigger trg_users_cascade_delete
  before delete on public.users
  for each row execute function public.cascade_delete_user_data();
