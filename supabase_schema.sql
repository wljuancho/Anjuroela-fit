-- Compatibilidad con instalaciones legacy donde 'user_id' aún era bigint
-- (FK del antiguo users(id)). Si alguna tabla con datos de usuario mantiene
-- la columna como bigint, se convierte a text y se re-direcciona su FK a
-- users(email) para que el upsert por correo y las políticas RLS funcionen.
-- Idempotente: sin columnas bigint remanentes no toca nada. Las filas
-- huérfanas (id numérico que ya no corresponde a ningún email) se descartan.
do $$
declare
  r record;
  con record;
begin
  for r in
    select t.table_name
    from information_schema.columns t
    where t.table_schema = 'public'
      and t.column_name = 'user_id'
      and t.data_type <> 'text'
  loop
    for con in
      select c.conname, tc.relname as table_name
      from pg_constraint c
      join pg_class tc on tc.oid = c.conrelid
      join pg_class rc on rc.oid = c.confrelid
      where c.contype = 'f'
        and tc.relname = r.table_name
        and rc.relname = 'users'
    loop
      execute 'alter table public.' || quote_ident(r.table_name)
        || ' drop constraint ' || quote_ident(con.conname);
    end loop;
    execute 'alter table public.' || quote_ident(r.table_name)
      || ' alter column user_id type text using user_id::text';
    execute 'delete from public.' || quote_ident(r.table_name)
      || ' where user_id::text not in (select email from public.users)';
    execute 'alter table public.' || quote_ident(r.table_name)
      || ' add constraint ' || quote_ident(r.table_name || '_user_fk')
      || ' foreign key (user_id) references public.users (email) on delete cascade';
  end loop;
end $$;

-- Identidad del usuario activo enviada por la app en la cabecera 'x-app-user'.
-- Las políticas RLS la usan para aislar los datos por usuario aunque la app
-- opere con la clave anónima (publishable). Devuelve '' (o null tras nullif)
-- cuando no hay sesión activa, negando el acceso a filas con propietario.
-- Patrón oficial de Supabase: current_setting('request.headers', true).
create or replace function public.app_user_email()
returns text
language sql
stable
as $$
  select nullif(current_setting('request.headers', true)::json ->> 'x-app-user', '')
$$;

