  using (
    not exists (
      select 1 from public.user_row_owners o
      where o.table_name = 'meal_logs' and o.row_id = meal_logs.id
    )
    or exists (
      select 1 from public.user_row_owners o
      where o.table_name = 'meal_logs' and o.row_id = meal_logs.id
        and o.user_id::text = public.app_user_email()
    )
  )
  with check (true);
