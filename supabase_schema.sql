-- Limpieza idempotente previa: si la tabla 'users' aún conserva la columna
-- legacy 'id' (estructura int8 con identidad), se elimina por completo el
-- conjunto de tablas que dependían de ella para que las definiciones
-- siguientes (basadas en email) se creen desde cero. Incluye meals_v2 y
-- user_row_owners porque ambas referenciaban users(id) mediante FK y, tras el
-- DROP CASCADE de users, mantendrían la columna legacy bigint que el
-- 'CREATE TABLE IF NOT EXISTS' posterior ya no corregiría.
-- Idempotente: en instalaciones ya migradas (sin 'id'), el bloque no hace nada.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'users' and column_name = 'id'
  ) then
    drop table if exists public.user_profiles cascade;
    drop table if exists public.nutrition_profile cascade;
    drop table if exists public.meals_v2 cascade;
    drop table if exists public.user_row_owners cascade;
    drop table if exists public.users cascade;
  end if;
end $$;

-- ---------------- usuarios ----------------
-- El EMAIL es la clave primaria (identidad unica de la cuenta, igual que en
-- SQLite local); el antiguo id identity queda fuera del modelo.
create table if not exists public.users (
  email text primary key,
  name text not null,
  password_hash text,
  auth_provider text default 'local',
  created_at text default (now()::text)
);

-- UNIQUE(email) (redundante con la PK) para compatibilidad con el upsert por
-- correo idempotente. Idempotente.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.users'::regclass
      and contype = 'u'
      and conname = 'users_email_key'
  ) then
    alter table public.users
      add constraint users_email_key unique (email);
  end if;
end $$;

