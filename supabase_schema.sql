  add column if not exists note text;

-- UNIQUE(day_of_week, date, session_type): una sesión de rutina + una ocasional
-- ('casual') pueden convivir el mismo día; el upsert por conflicto compuesto
-- desde la app es idempotente. Se reemplaza la antigua unicidad por día+date.
do $$
begin
  if exists (
    select 1 from pg_constraint
    where conrelid = 'public.workout_sessions'::regclass
      and contype = 'u'
      and conname = 'workout_sessions_day_date_unique'
  ) then
    alter table public.workout_sessions
      drop constraint workout_sessions_day_date_unique;
  end if;
end $$;
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.workout_sessions'::regclass
      and contype = 'u'
      and conname = 'workout_sessions_day_date_type_unique'
  ) then
    alter table public.workout_sessions
      add constraint workout_sessions_day_date_type_unique
        unique (day_of_week, date, session_type);
